CREATE TABLE payments (
    id           UUID         PRIMARY KEY,            -- generated by the app
    merchant_id  VARCHAR(64)  NOT NULL,
    order_id     VARCHAR(64)  NOT NULL,
    amount       BIGINT       NOT NULL CHECK (amount > 0),   -- minor units (paise)
    currency     CHAR(3)      NOT NULL,
    status       VARCHAR(20)  NOT NULL
                 CHECK (status IN ('CREATED','PROCESSING','UNKNOWN','CAPTURED','FAILED')),
    version      INTEGER      NOT NULL DEFAULT 0,     -- for @Version later
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Invariant 4: at most one active/successful payment per order
CREATE UNIQUE INDEX one_active_payment_per_order
    ON payments (merchant_id, order_id)
    WHERE status IN ('CREATED','PROCESSING','UNKNOWN','CAPTURED');

CREATE TABLE idempotency_keys (
    merchant_id      VARCHAR(64)  NOT NULL,
    operation        VARCHAR(32)  NOT NULL,
    idem_key         VARCHAR(128) NOT NULL,
    fingerprint      CHAR(64)     NOT NULL,           -- SHA-256 hex
    status           VARCHAR(16)  NOT NULL
                     CHECK (status IN ('IN_PROGRESS','COMPLETED')),
    payment_id       UUID         REFERENCES payments (id)
                     DEFERRABLE INITIALLY DEFERRED,
    response_status  INTEGER,
    response_body    JSONB,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at       TIMESTAMPTZ  NOT NULL,
    PRIMARY KEY (merchant_id, operation, idem_key)    -- invariant 1: the race arbiter
);

CREATE INDEX idx_idempotency_keys_expires_at ON idempotency_keys (expires_at);